import usb.core, sys
dev = usb.core.find(idVendor=0x1209, idProduct=0x0002)
try: dev.set_configuration()
except: pass
d = dev.ctrl_transfer(0xC0, 0xFE, 0, 0, 16, timeout=1500)
p1 = d[0] | (d[1] << 8)
pcfg = d[2] | (d[3] << 8)
pbuf = d[4] | (d[5] << 8)
pmaxp = d[6] | (d[7] << 8)
bs = d[8] | (d[9] << 8)
rs = d[10] | (d[11] << 8)
ns = d[12] | (d[13] << 8)
fs = d[14] | (d[15] << 8)
pid_name = {0:'NAK',1:'BUF',2:'STALL',3:'STALL'}.get(p1&3, '?')
print(f"PIPE1CTR=0x{p1:04X} PID={pid_name} BSTS={(p1>>15)&1} INBUFM={(p1>>13)&1} SQMON={(p1>>7)&1}")
print(f"PIPECFG=0x{pcfg:04X} TYPE={(pcfg>>14)&3} BFRE={(pcfg>>10)&1} DBLB={(pcfg>>9)&1} SHTNAK={(pcfg>>7)&1} DIR={(pcfg>>4)&1} EPNUM={pcfg&0xF}")
print(f"PIPEBUF=0x{pbuf:04X} BUFSIZE={(pbuf>>10)&0x1F} BUFNMB={pbuf&0xFF}")
print(f"PIPEMAXP=0x{pmaxp:04X}")
print(f"BEMPSTS=0x{bs:04X} BRDYSTS=0x{rs:04X} NRDYSTS=0x{ns:04X}")
print(f"CFIFOSEL=0x{fs:04X} CURPIPE={fs&0xF} ISEL={(fs>>5)&1} MBW={(fs>>10)&1} RCNT={(fs>>14)&1}")
